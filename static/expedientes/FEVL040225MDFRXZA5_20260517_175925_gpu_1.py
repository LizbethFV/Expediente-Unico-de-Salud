import time
import numpy as np
from tensorflow.keras import Sequential
from tensorflow.keras.layers import Conv2D, MaxPooling2D, Flatten, Dense
import matplotlib.pyplot as plt
import tensorflow as tf

# Verificación opcional para confirmar que estamos en CPU
print("Dispositivos disponibles:", tf.config.list_physical_devices())

class TimeHistory(tf.keras.callbacks.Callback):#Begin y end registran el tiempo que tarda en procesar los datos (antes y depues)
    def on_train_begin(self, logs=None):
        self.times = []
    def on_epoch_begin(self, epoch, logs=None):
        self.t0 = time.perf_counter()
    def on_epoch_end(self, epoch, logs=None):
        dt = time.perf_counter() - self.t0
        self.times.append(dt)
        print(f"[tiempo] Época {epoch+1}: {dt:.3f} s")

time_cb = TimeHistory()

# Carga de datos
# El datamnist contiene 60 000 imagenes de numeros del 0 al 9
(X_train, y_train), (X_test, y_test) = tf.keras.datasets.mnist.load_data()

# Normalización
X_train = X_train.astype("float32") / 255.0 # Normalizamos los pixeles al dividirlos los dejamos en un rango del 0 al 1 lo que permite que lo calculos matematicos sean mas rapidos
X_test = X_test.astype("float32") / 255.0

# Añadir dimensión de canal (MNIST es escala de grises)
X_train = X_train[..., np.newaxis]
X_test = X_test[..., np.newaxis]

# Definición del modelo
model = Sequential([
    Conv2D(32, (3,3), activation="relu", input_shape=(28,28,1)), #Tensorflow espera una cuarta dimesión, ya que las imagenes son de 28x28
    MaxPooling2D((2,2)),
    Conv2D(64, (3,3), activation="relu"),#Son filtros que buscan patrone (lineas, curvas)
    MaxPooling2D((2,2)),# Reduce el tamaño de la imagen, quedandose solo con lo mas importante
    Flatten(),
    Dense(64, activation="relu"),
    Dense(10, activation="softmax")
    #Decide si las imagenes corresponden a 3,8,5
])
# Aqui elegimos el optimizador
model.compile(
    loss="sparse_categorical_crossentropy",#Funcion de perdida que mide que tan equivocado esta el modelo
    optimizer=tf.keras.optimizers.Adam(learning_rate=0.001),# Adam es el mtor que ajusta los pesos
    metrics=["accuracy"]
)

# Entrenamiento
print("Iniciando entrenamiento en CPU...")
t0_total = time.perf_counter()
history = model.fit( # Es el proceso de aprendizaje
    X_train, y_train,
    epochs=10,
    batch_size=64,
    validation_split=0.2,
    verbose=1,
    callbacks=[time_cb]
)
t1_total = time.perf_counter()

# Resultados de tiempo
print("\n--- Resultados de Rendimiento en CPU ---")
print("Tiempos por época:", [round(t,3) for t in time_cb.times])
print("Promedio por época:", round(sum(time_cb.times)/len(time_cb.times),3), "s")
print("Tiempo total:", round(t1_total - t0_total,3), "s")

# Evaluación
test_loss, test_acc = model.evaluate(X_test, y_test, verbose=0)
print(f"Test accuracy: {round(float(test_acc), 4)}")

