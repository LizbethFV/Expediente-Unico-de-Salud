import time
import torch

N = 20_000_000 #Creamos vectores de 20_000_000

#Generamos un tensor de namaño N, con numeros aleatorios, el cual se crea en CPU (RAM), son vectores de varias dimenciones
x_cpu = torch.rand(N) #generamos 2 vectores
y_cpu = torch.rand(N)

# Porcedemos a cuantificar la suma de dichos vectores
t0 = time.perf_counter()
z_cpu = x_cpu + y_cpu
t1 = time.perf_counter()
print("Suma en CPU: ", round(t1 - t0, 4),"s")

#GPU
if torch.cuda.is_available(): #¿Hay GPU disponible?
  x_gpu = x_cpu.to("cuda") #Copiar los tensores desde CPU (RAM) hacia GPU (VRAM)
  y_gpu = y_cpu.to("cuda")
  #Lo anterior implica que ahora las operaciones viviran en GPU
  _ = x_gpu + y_gpu # La primera operacion realizara en GPU puede ser lenta
  #Por inicializaciones internas y por lo tanto, al colocarle "_" indicamos que
  #nos interesa guardar el primer resultado
  torch.cuda.synchronize() #Espera a que la GPU termine para medir el tiempo

  t0 = time.perf_counter()
  z_cpu = x_cpu + y_cpu
  t1 = time.perf_counter()
  print("Suma en CPU: ", round(t1 - t0, 4),"s")

